import { gzipSync, strToU8 } from "fflate";
import { describe, expect, it } from "vitest";
import { parseDnaFileCore } from "../src/ui/dna-import/parseCore.js";
import { concatBytes, fakeFile } from "./genomics-fixtures.js";

/**
 * The worker path and the main-thread path must be the *same* parser.
 *
 * `parseFile.js` runs `parseDnaFileCore` with `cooperative: false` inside a Web
 * Worker and with `cooperative: true` when it has to fall back to the main
 * thread. Everything else about the two calls is identical, and this suite is
 * what keeps it that way: it parses the same bytes both ways and requires the
 * results to match exactly.
 *
 * Without this, a fallback-only host (one whose CSP blocks the `blob:` worker)
 * could silently produce different variants from a worker-capable host.
 */

/** Two microarray markers, one alias, and one non-SNV WGS capture target. */
const CATALOG = {
  version: 1,
  snp_count: 3,
  snps: {
    rs328: {
      rsID: "rs328",
      chromosome: "8",
      position_GRCh37: 19819724,
      position_GRCh38: 19962213,
      risk_allele: "A",
    },
    rs671: {
      rsID: "rs671",
      chromosome: "12",
      position_GRCh37: 112241766,
      position_GRCh38: 111803962,
      risk_allele: "A",
    },
    rs999999001: {
      rsID: "rs999999001",
      chromosome: "16",
      position_GRCh37: 50745926,
      position_GRCh38: 50729867,
      risk_allele: "C",
      wgs_capture: {
        schema_version: 1,
        variant_class: "non_snv",
        capture_mode: "raw_vcf_record",
        capture_range_GRCh37: { start: 50745920, end: 50745930 },
        capture_range_GRCh38: { start: 50729860, end: 50729870 },
      },
    },
  },
  aliases: { rs671: ["rs2230021"] },
};

const VCF_COLUMNS = "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSAMPLE";

/** One fixture per code path: rsID matching, coordinates, gzip, and no matches. */
const FIXTURES: Array<[string, () => File]> = [
  [
    "23andMe microarray",
    () =>
      fakeFile(
        "23andme.txt",
        [
          "# This data was generated by 23andMe",
          "# rsid\tchromosome\tposition\tgenotype",
          "rs328\t8\t19819724\tAA",
          "rs2230021\t12\t112241766\tGA",
          "rs671\t12\t112241766\t--",
        ].join("\n"),
      ),
  ],
  [
    "Ancestry microarray",
    () =>
      fakeFile(
        "ancestry.txt",
        [
          "# rsid\tchromosome\tposition\tallele1\tallele2",
          "rs328\t8\t19819724\tA\tG",
          "rs671\t12\t112241766\tG\tG",
        ].join("\n"),
      ),
  ],
  [
    "plain VCF with a non-SNV capture record",
    () =>
      fakeFile(
        "sample.vcf",
        [
          "##fileformat=VCFv4.2",
          "##reference=GRCh38",
          VCF_COLUMNS,
          "8\t19962213\t.\tA\tG\t.\tPASS\t.\tGT:DP\t0/1:25",
          "16\t50729867\trs999999001\tG\tGC\t123.4\tPASS\t.\tGT:DP:GQ:AD\t0/1:32:99:18,14",
        ].join("\n"),
      ),
  ],
  [
    "gzipped VCF split across concatenated gzip members",
    () => {
      const header = `${["##fileformat=VCFv4.2", "##reference=GRCh37", VCF_COLUMNS].join("\n")}\n`;
      const body = ["8\t19819724\t.\tA\tG\t.\tPASS\t.\tGT\t1/1", ""].join("\n");
      return fakeFile(
        "sample.vcf.gz",
        concatBytes(gzipSync(strToU8(header)), gzipSync(strToU8(body))),
      );
    },
  ],
  [
    "VCF with no catalog matches",
    () =>
      fakeFile(
        "nomatch.vcf",
        [VCF_COLUMNS, "1\t1000\t.\tA\tG\t.\tPASS\t.\tGT\t0/1", ""].join("\n"),
      ),
  ],
];

describe("parser parity: worker path vs main-thread path", () => {
  for (const [label, makeFile] of FIXTURES) {
    it(`produces identical output with cooperative yielding on and off: ${label}`, async () => {
      const onMainThread = await parseDnaFileCore(makeFile(), {
        catalog: CATALOG,
        cooperative: true,
      });
      const inWorker = await parseDnaFileCore(makeFile(), { catalog: CATALOG, cooperative: false });

      // A `supported` mismatch would mean the streaming pipeline itself behaves
      // differently per mode, and every other field would be meaningless.
      expect(onMainThread.supported).toBe(true);
      expect(inWorker).toEqual(onMainThread);
    });
  }

  it("reports the same progress from both paths", async () => {
    const makeFile = FIXTURES[0]![1];
    const mainProgress: number[] = [];
    const workerProgress: number[] = [];

    await parseDnaFileCore(makeFile(), {
      catalog: CATALOG,
      cooperative: true,
      onProgress: (percent) => mainProgress.push(percent),
    });
    await parseDnaFileCore(makeFile(), {
      catalog: CATALOG,
      cooperative: false,
      onProgress: (percent) => workerProgress.push(percent),
    });

    expect(workerProgress).toEqual(mainProgress);
    expect(mainProgress.length).toBeGreaterThan(0);
  });

  it("agrees on the unsupported-client shape", async () => {
    // `supportsStreaming()` is a capability probe, so both paths must agree on
    // the answer rather than one of them throwing.
    const savedFile = globalThis.File;
    // @ts-expect-error - simulate a browser without the Streams-capable File API.
    delete globalThis.File;
    try {
      const file = { name: "23andme.txt", size: 0 } as unknown as File;
      const onMainThread = await parseDnaFileCore(file, { catalog: CATALOG, cooperative: true });
      const inWorker = await parseDnaFileCore(file, { catalog: CATALOG, cooperative: false });
      expect(inWorker).toEqual(onMainThread);
      expect(onMainThread.supported).toBe(false);
    } finally {
      globalThis.File = savedFile;
    }
  });
});
